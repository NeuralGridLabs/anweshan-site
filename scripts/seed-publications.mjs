/* --------------------------------------------------------------------------
   3. Stable document IDs (same algorithm as migration-manifest.mjs)
   ----------------------------------------------------------------------- */
function slugify(value) {
  return String(value)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function publicationIdFor(title) {
  return `publication-${slugify(title)}`;
}

