async function upsertPublication(pub) {
  const docId = publicationIdFor(pub.title);
  
  const doc = {
    _id: docId,
    _type: "publication",
    title: pub.title,
    authors: pub.authors,
    year: pub.year,
    journal: pub.journal || undefined,
    abstract: pub.abstract,
    type: pub.type,
    topic: pub.topic || [],
    geography: pub.geography || [],
    anweshanRole: pub.anweshanRole,
    roleExplanation: pub.roleExplanation,
    client: pub.client || undefined,
    partner: pub.partner || undefined,
    funder: pub.funder || undefined,
    citation: pub.citation || undefined,
    doi: pub.doi || undefined,
    accessStatus: pub.accessStatus,
    order: pub.order,
    featuredOnHome: pub.featuredOnHome || false,
    // file and externalUrl left empty - files would be uploaded separately
    // coverImage left empty - would be uploaded separately
  };

  if (DRY_RUN) {
    console.log(`[DRY RUN] Would upsert: ${pub.title} (${docId})`);
    return { id: docId, title: pub.title, dryRun: true };
  }

  try {
    const result = await client.createIfNotExists(doc);
    console.log(`✓ Created/updated: ${pub.title}`);
    return result;
  } catch (err) {
    console.error(`✗ Failed: ${pub.title}`);
    console.error(err.message);
    return null;
  }
}

async function main() {
  console.log(`\nSeeding ${publications.length} publications...\n`);
  
  let success = 0;
  let failed = 0;
  
  for (const pub of publications) {
    const result = await upsertPublication(pub);
    if (result) success++;
    else failed++;
  }
  
  console.log(`\n--- Summary ---`);
  console.log(`Total: ${publications.length}`);
  console.log(`Success: ${success}`);
  console.log(`Failed: ${failed}`);
  console.log(`Mode: ${DRY_RUN ? "DRY RUN (use --apply to write)" : "APPLIED"}`);
}

main().catch((err) => {
  console.error("Fatal error:", err);
  process.exit(1);
});